#!/usr/bin/env node
// Playwright's planner, generator and healer agents for Claude, adapted for the kit (spec:
// Packaging, From scenario to test code). `playwright init-agents --loop=claude` writes the stock
// definitions into the kit's Playwright project (.claude/agents/playwright-test-*.md, .mcp.json)
// and overwrites them on every upgrade, so the kit's changes live in agents/kit.patch and are
// applied after every init.
//
// usage: node living-manual/kit/bin/lm-agents.mjs init        stock agents, then the patch (setup runs this)
//        node living-manual/kit/bin/lm-agents.mjs apply       the patch only (after `playwright init-agents`)
//        node living-manual/kit/bin/lm-agents.mjs make-patch  rewrite agents/kit.patch from the current files
//        any of them with --kit <dir> to act on another copy of the kit (the kit's tests do)
// Exit 0 OK, 1 the patch does not apply, 2 usage. Last line: `agents OK: …` or `agents FAIL: …`.
import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const FILES = ['.claude/agents/playwright-test-planner.md', '.claude/agents/playwright-test-generator.md',
	'.claude/agents/playwright-test-healer.md', '.mcp.json'];
const PATCH = 'agents/kit.patch';

const args = process.argv.slice(2);
const k = args.indexOf('--kit');
const kit = resolve(k >= 0 ? args.splice(k, 2)[1] : join(dirname(fileURLToPath(import.meta.url)), '..'));
const [command] = args;
const say = (line) => console.log(line);

/** Runs Playwright's init-agents for Claude in `dir`. Its config only names a throw-away seed folder. */
function stockInit(dir) {
	const scratch = mkdtempSync(join(tmpdir(), 'lm-agents-init-'));
	writeFileSync(join(scratch, 'playwright.config.mjs'), `export default { testDir: ${JSON.stringify(scratch)}, projects: [{ name: 'kit' }] };\n`);
	const hadSpecs = existsSync(join(dir, 'specs'));
	const r = spawnSync(join(kit, 'node_modules/.bin/playwright'), ['init-agents', '--loop=claude', '--config', join(scratch, 'playwright.config.mjs')], { cwd: dir, encoding: 'utf8' });
	rmSync(scratch, { recursive: true, force: true });
	if (!hadSpecs) rmSync(join(dir, 'specs'), { recursive: true, force: true }); // the stock plan folder; the kit plans into .feature files
	if (r.status !== 0) { say(`${r.stdout}${r.stderr}`); say('agents FAIL: playwright init-agents failed'); process.exit(1); }
}

const version = () => JSON.parse(readFileSync(join(kit, 'node_modules/@playwright/test/package.json'), 'utf8')).version;
const patch = (...a) => spawnSync('patch', ['-p1', '--batch', '--silent', '--input', join(kit, PATCH), ...a], { cwd: kit, encoding: 'utf8' });

/** Applies the patch; refuses (files untouched) when it does not fit. */
function apply() {
	if (patch('--reverse', '--forward', '--dry-run').status === 0) return 'already'; // --forward: never flip direction on its own
	const check = patch('--forward', '--dry-run');
	if (check.status !== 0) {
		say(`${check.stdout}${check.stderr}`.trim());
		say(`agents FAIL: ${PATCH} does not apply to the agents Playwright ${version()} wrote. Merge the kit's changes into the new stock files by hand, then run make-patch`);
		process.exit(1);
	}
	const r = patch('--forward', '--no-backup-if-mismatch');
	if (r.status !== 0) { say(`${r.stdout}${r.stderr}`); say(`agents FAIL: ${PATCH} failed to apply`); process.exit(1); }
	for (const f of FILES) rmSync(join(kit, `${f}.orig`), { force: true });
	return 'applied';
}

if (command === 'init') {
	stockInit(kit);
	apply();
	say(`agents OK: initialised Playwright ${version()} agents for Claude and applied ${PATCH}`);
} else if (command === 'apply') {
	say(apply() === 'already' ? `agents OK: ${PATCH} is already applied` : `agents OK: applied ${PATCH}`);
} else if (command === 'make-patch') {
	const stock = mkdtempSync(join(tmpdir(), 'lm-agents-stock-'));
	stockInit(stock);
	let out = `# The kit's changes to Playwright ${version()}'s agents for Claude (bin/lm-agents.mjs). Generated by\n# \`lm-agents.mjs make-patch\`; edit the agent files, never this patch.\n`;
	for (const f of FILES) {
		const d = spawnSync('diff', ['-u', '--label', `a/${f}`, '--label', `b/${f}`, join(stock, f), join(kit, f)], { encoding: 'utf8' });
		if (d.status > 1) { say(d.stderr); process.exit(1); }
		out += d.stdout;
	}
	rmSync(stock, { recursive: true, force: true });
	mkdirSync(join(kit, 'agents'), { recursive: true });
	writeFileSync(join(kit, PATCH), out);
	say(`agents OK: wrote ${PATCH} (${out.split('\n').filter((l) => l.startsWith('+++')).length} file(s) changed)`);
} else {
	process.stderr.write('usage: lm-agents.mjs init | apply | make-patch [--kit <dir>]\n');
	process.exit(2);
}
