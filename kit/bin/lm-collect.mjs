#!/usr/bin/env node
// Checks the case inventory the planner wrote (facts/cases.json; spec: Solution 2, Facts pack)
// and writes facts/cases.md: every case by area, the doc scenario covering it or "not yet
// covered", and the human text that stated its intent, if any.
//
// usage: node living-manual/kit/bin/lm-collect.mjs <product>   (or --folder <product folder>)
// Exit 0 PASS, 1 FAIL, 2 usage. Last line: `collect PASS: …` or `collect FAIL: …`.
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { folderFromArgs } from './lib/workspace.mjs';
import { docScenarios, readInventory } from './lib/cases.mjs';

let folder, inventory;
try {
	({ folder } = folderFromArgs(process.argv.slice(2)));
	inventory = readInventory(folder);
} catch (e) {
	process.stderr.write(`lm-collect: ${e.message}\nusage: lm-collect.mjs <product> | --folder <dir>\n`);
	process.exit(2);
}

const scenarios = new Map(docScenarios(folder).map((s) => [s.id, s]));
const cases = inventory.cases ?? [];
const problems = [];
const seen = new Set();
for (const c of cases) {
	const id = c.id ?? '(no id)';
	if (seen.has(id)) problems.push(`${id}: case id used twice`);
	seen.add(id);
	for (const key of ['area', 'title', 'role', 'startScreen']) if (!c[key]) problems.push(`${id}: no ${key}`);
	if (!c.evidence?.length) problems.push(`${id}: no evidence (the code file and line, or the screen, that shows the case)`);
	if (c.scenario && !scenarios.has(c.scenario)) problems.push(`${id}: scenario ${c.scenario} is not a doc scenario in scenarios/*.feature`);
}

for (const p of problems) console.log(`  ${p}`);
if (problems.length) {
	console.log(`collect FAIL: ${problems.length} problem(s) in ${cases.length} case(s)`);
	process.exit(1);
}

const areas = [...new Set(cases.map((c) => c.area))];
const covered = cases.filter((c) => c.scenario).length;
const cell = (s) => String(s).replace(/\|/g, '\\|');
let md = `# Case inventory: ${inventory.product ?? ''}\n\nEvery case a user can perform, from facts/cases.json (written by the planner). Generated by lm-collect; edit cases.json, not this file.\n\n${cases.length} case(s) in ${areas.length} area(s); ${covered} covered by a doc scenario, ${cases.length - covered} not yet.\n`;
for (const area of areas) {
	md += `\n## ${area}\n\n| Case | Role | Starts on | Doc scenario | Intent stated by |\n|---|---|---|---|---|\n`;
	for (const c of cases.filter((x) => x.area === area)) {
		const scenario = c.scenario ?? `not yet covered${c.manual ? ` (@manual: ${c.manual})` : ''}`;
		const intent = c.humanIntent ? `${c.humanIntent.type} ${c.humanIntent.location}` : 'none: app and code only';
		md += `| ${cell(c.title)} | ${cell(c.role)} | ${cell(c.startScreen)} | ${cell(scenario)} | ${cell(intent)} |\n`;
	}
}
writeFileSync(join(folder, 'facts/cases.md'), md);
console.log(`collect PASS: ${cases.length} case(s) in ${areas.length} area(s); ${covered} covered by a doc scenario, ${cases.length - covered} not yet`);
